function readme(t: ThemeSettings): string {
  const w = wallpaperById(t.wallpaper)
  return `# ${t.name} — Windows 11 Liquid Glass theme
Generated with Liquid Glass Studio.

## What's in this pack
- ${slug(t.name)}.theme   Windows theme definition (colors, wallpaper, dark/light mode)
- wallpaper.jpg            ${w.name} — ${w.note}
- glass-tokens.css         The exact glass recipe as CSS custom properties
- preset.json              All settings, for re-import into the Studio
- install.ps1              One-step installer for Windows 11

## Install (Windows 11)
1. Unzip this folder somewhere permanent.
2. Right-click **install.ps1** → *Run with PowerShell*
   (or run:  powershell -ExecutionPolicy Bypass -File .\\install.ps1)
3. Windows applies the theme and wallpaper immediately.

Manual route: copy this folder to
  %LOCALAPPDATA%\\Microsoft\\Windows\\Themes\\
then double-click **${slug(t.name)}.theme**.

## Glass recipe
- Blur:          ${t.glass.blur}px
- Saturation:    ${t.glass.saturation}%
- Brightness:    ${t.glass.brightness}%
- Tint:          ${t.glass.tint} @ ${t.glass.opacity}% opacity
- Corner radius: ${t.glass.radius}px
- Rim:           ${t.glass.rim}px  ·  Specular ${t.glass.specular}%
- Shadow:        ${t.glass.shadow}%  ·  Grain ${t.glass.noise}%
- Accent:        ${t.accent}   ·  Mode: ${t.mode}

## Important — how far Windows goes natively
A .theme file controls wallpaper, accent colour, mode and cursors. Windows 11's own
acrylic/mica is applied by the compositor; it cannot be replaced by a .theme file.

For deeper liquid-glass effects, pair this pack with one of:
- **Windhawk** (mods: "Windows 11 Taskbar Styler", "Dark mode for Mica")
- **DWMBlurGlass** (custom acrylic/blur parameters for DWM)
- **StartAllBack** or **ExplorerPatcher** (window frame + taskbar styling)
- **TranslucentTB** (taskbar transparency; use "acrylic" for a glass taskbar)

Windows Settings → Personalization → Colors → **Transparency effects** must be ON
for the built-in acrylic to appear behind Start, the taskbar and flyouts.

The glass-tokens.css file contains the same recipe used by the Studio preview, ready
for web projects, Electron apps or any UI you want to match.

Made with Liquid Glass Studio.
`
}

function installPs1(t: ThemeSettings): string {
  const name = slug(t.name)
  return `# ${t.name} — installer (Windows 11)
# Copies the theme to your user Themes folder and applies it.
$ErrorActionPreference = 'Stop'
$src  = Split-Path -Parent $MyInvocation.MyCommand.Path
$dest = Join-Path $env:LOCALAPPDATA "Microsoft\\Windows\\Themes\\${name}"

New-Item -ItemType Directory -Force -Path $dest | Out-Null
Copy-Item (Join-Path $src 'wallpaper.jpg') $dest -Force
Copy-Item (Join-Path $src '${name}.theme') $dest -Force

Write-Host ""
Write-Host "  ${t.name}" -ForegroundColor Cyan
Write-Host "  Installed to: $dest" -ForegroundColor DarkGray
Write-Host ""
Write-Host "  Applying theme..." -ForegroundColor Green

Start-Process (Join-Path $dest '${name}.theme')

Write-Host "  Done. If Windows asks how to open the file, choose Windows."
Write-Host "  For the full glass look, enable Settings > Personalization > Colors > Transparency effects."
Write-Host ""
`
}

export async function buildThemeZip(t: ThemeSettings): Promise<Blob> {
  const zip = new JSZip()
  const root = zip.folder(slug(t.name))!
  const w = wallpaperById(t.wallpaper)

  root.file(`${slug(t.name)}.theme`, themeIni(t))
  root.file('README.md', readme(t))
  root.file('install.ps1', installPs1(t))
  root.file('glass-tokens.css', `/* ${t.name} — glass recipe */\n` + toGlassCss(t))
  root.file(
    'preset.json',
    JSON.stringify(
      {
        generator: 'Liquid Glass Studio',
        version: 1,
        exportedAt: new Date().toISOString(),
        wallpaperFile: 'wallpaper.jpg',
        theme: t,
        windowsTheme: {
          mode: t.mode,
          accent: t.accent,
          transparencyEffects: t.glass.opacity < 80,
        },
      },
      null,
      2,
    ),
  )

  try {
    const res = await fetch(w.src)
    if (res.ok) {
      const buf = await res.arrayBuffer()
      root.file('wallpaper.jpg', buf)
    }
  } catch {
    // offline: still ship the rest of the pack
  }

  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE' })
}

function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 4000)
}

export async function downloadThemeZip(t: ThemeSettings) {
  const blob = await buildThemeZip(t)
  triggerDownload(blob, `${slug(t.name)}-Windows11-Theme.zip`)
}

export async function downloadWallpaper(t: ThemeSettings) {
  const w = wallpaperById(t.wallpaper)
  try {
    const res = await fetch(w.src)
    const blob = await res.blob()
    triggerDownload(blob, `${w.name.replace(/\s+/g, '-')}-2560x1440.jpg`)
  } catch {
    window.open(w.src, '_blank')
  }
}

export async function copyText(text: string) {
  try {
    await navigator.clipboard.writeText(text)
    return true
  } catch {
    const ta = document.createElement('textarea')
    ta.value = text
    ta.style.position = 'fixed'
    ta.style.opacity = '0'
    document.body.appendChild(ta)
    ta.select()
    const ok = document.execCommand('copy')
    ta.remove()
    return ok
  }
}

export function presetJson(t: ThemeSettings) {
  return JSON.stringify(t, null, 2)
}
