import type { ThemeSettings } from './types'

export function hexToRgb(hex: string): [number, number, number] {
  let h = hex.replace('#', '').trim()
  if (h.length === 3) h = h.split('').map((c) => c + c).join('')
  const n = parseInt(h || '000000', 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

export function rgba(hex: string, alpha: number): string {
  const [r, g, b] = hexToRgb(hex)
  return `rgba(${r}, ${g}, ${b}, ${alpha})`
}

export function mix(a: string, b: string, t: number): string {
  const A = hexToRgb(a)
  const B = hexToRgb(b)
  const c = A.map((v, i) => Math.round(v + (B[i] - v) * t))
  return `#${c.map((v) => v.toString(16).padStart(2, '0')).join('')}`
}

export function luminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex).map((v) => {
    const s = v / 255
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

/** All design tokens the glass UI and exported CSS share. */
export function themeVars(t: ThemeSettings): Record<string, string> {
  const dark = t.mode === 'dark'
  const g = t.glass
  const alpha = g.opacity / 100
  const glassA = dark ? alpha : Math.min(0.9, alpha * 1.15 + 0.05)
  const text = dark ? '#f4f7fd' : '#111827'
  const dim = dark ? rgba('#dbe4f5', 0.72) : rgba('#111827', 0.68)
  const faint = dark ? rgba('#dbe4f5', 0.38) : rgba('#111827', 0.42)
  const line = dark ? rgba('#ffffff', 0.11) : rgba('#0b1220', 0.1)
  const lineStrong = dark ? rgba('#ffffff', 0.2) : rgba('#0b1220', 0.16)
  const base = dark ? '#0b0f19' : '#f4f7fb'
  const surface = dark ? rgba('#0a0e18', 0.55) : rgba('#ffffff', 0.66)
  const hover = dark ? rgba('#ffffff', 0.08) : rgba('#0b1220', 0.06)
  const active = dark ? rgba('#ffffff', 0.14) : rgba('#0b1220', 0.11)
  const accentOn = luminance(t.accent) > 0.55 ? '#0a0f18' : '#ffffff'

  return {
    '--glass-blur': `${g.blur}px`,
    '--glass-sat': `${g.saturation}%`,
    '--glass-bright': `${g.brightness}%`,
    '--glass-alpha': glassA.toFixed(3),
    '--glass-tint': g.tint,
    '--glass-tint-rgb': hexToRgb(g.tint).join(', '),
    /* depth shade keeps text legible over bright wallpapers */
    '--glass-shade': dark
      ? `rgba(6, 9, 16, ${(0.5 - alpha * 0.22).toFixed(3)})`
      : `rgba(255, 255, 255, ${(0.42 - alpha * 0.18).toFixed(3)})`,
    '--radius': `${g.radius}px`,
    '--rim': `${g.rim}`,
    '--spec': (g.specular / 100).toFixed(3),
    '--shadow-strength': (g.shadow / 100).toFixed(3),
    '--noise': (g.noise / 100).toFixed(3),
    '--lens': `${g.lens / 100}`,
    '--lens-blur': `${(g.lens / 100) * 3 + 0.4}px`,
    '--lens-bright': `${1 + (g.lens / 100) * 0.55}`,
    '--accent': t.accent,
    '--accent-rgb': hexToRgb(t.accent).join(', '),
    '--accent-soft': rgba(t.accent, dark ? 0.16 : 0.13),
    '--accent-on': accentOn,
    '--text': text,
    '--text-dim': dim,
    '--text-faint': faint,
    '--line': line,
    '--line-strong': lineStrong,
    '--base': base,
    '--surface': surface,
    '--hover': hover,
    '--active': active,
    '--wallpaper-dim': `${t.wallpaperDim / 100}`,
    '--wallpaper-blur': `${t.wallpaperBlur}px`,
    '--radius-sm': `${Math.max(4, g.radius - 6)}px`,
    '--radius-lg': `${g.radius + 6}px`,
    '--titlebar-h': '42px',
  }
}

export function applyThemeVars(root: HTMLElement, t: ThemeSettings) {
  const vars = themeVars(t)
  for (const [k, v] of Object.entries(vars)) root.style.setProperty(k, v)
  root.dataset.mode = t.mode
}

export function toGlassCss(t: ThemeSettings): string {
  const vars = themeVars(t)
  const body = Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')
  return `/* ${t.name} — generated by Liquid Glass Studio */
:root[data-theme="liquid-glass"] {
${body}
}

/* The glass surface itself */
.glass {
  position: relative;
  isolation: isolate;
  background:
    radial-gradient(140% 120% at 100% 0%, rgba(var(--accent-rgb), 0.14), transparent 55%),
    linear-gradient(150deg,
      rgba(var(--glass-tint-rgb), calc(var(--glass-alpha) * 1.35)),
      rgba(var(--glass-tint-rgb), calc(var(--glass-alpha) * 0.72))),
    linear-gradient(var(--glass-shade), var(--glass-shade));
  -webkit-backdrop-filter: blur(var(--glass-blur)) saturate(var(--glass-sat)) brightness(var(--glass-bright));
  backdrop-filter: blur(var(--glass-blur)) saturate(var(--glass-sat)) brightness(var(--glass-bright));
  border: 1px solid var(--line);
  border-radius: var(--radius);
  box-shadow:
    0 28px 60px -22px rgba(0, 0, 0, calc(var(--shadow-strength) * 0.9)),
    0 2px 10px rgba(0, 0, 0, calc(var(--shadow-strength) * 0.25)),
    inset 0 1px 0 rgba(255, 255, 255, calc(var(--spec) * 0.8)),
    inset 0 -1px 0 rgba(255, 255, 255, calc(var(--spec) * 0.16));
  color: var(--text);
}

.glass::after {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  pointer-events: none;
  background:
    linear-gradient(calc(120deg + var(--light-angle, 0deg)),
      rgba(255, 255, 255, calc(var(--spec) * 0.5)) 0%,
      rgba(255, 255, 255, calc(var(--spec) * 0.08)) 22%,
      transparent 46%);
  mix-blend-mode: screen;
  opacity: 0.9;
}
`
}
