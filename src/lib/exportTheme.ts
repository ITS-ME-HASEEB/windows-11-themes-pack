import JSZip from 'jszip'
import type { ThemeSettings } from './types'
import { toGlassCss } from './theme'
import { wallpaperById } from './wallpapers'

const slug = (s: string) =>
  s.replace(/[\\/:*?"<>|]/g, '').replace(/\s+/g, ' ').trim() || 'Liquid Glass'

